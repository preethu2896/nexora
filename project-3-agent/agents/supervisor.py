"""Supervisor Agent: Output normalization, response formatting, and validation."""

import time
from typing import Dict, Any, Optional, List
from config import config
from utils.logger import get_logger
from utils.exceptions import SupervisorError

logger = get_logger("supervisor_agent", config.log_level)


class SupervisorAgent:
    """Supervisor Agent responsible for validation, output normalization, and metrics aggregation."""

    def __init__(self):
        """Initializes Supervisor Agent."""
        pass

    def validate_input(self, user_query: str) -> Dict[str, Any]:
        """Validates incoming user request before processing.

        Args:
            user_query: Input string.

        Returns:
            Validation dictionary with status and start timestamp.
        """
        logger.info(f"SupervisorAgent validating input query (len={len(user_query)})...")
        if not user_query or not user_query.strip():
            raise SupervisorError("User query cannot be empty or whitespace.")

        return {
            "valid": True,
            "start_time": time.time(),
            "query_length": len(user_query.strip()),
        }

    def format_final_output(
        self,
        raw_response: Optional[str],
        route: Optional[str],
        citations: Optional[List[Dict[str, Any]]] = None,
        tool_calls: Optional[List[Dict[str, Any]]] = None,
        error: Optional[str] = None,
        start_time: Optional[float] = None,
    ) -> Dict[str, Any]:
        """Validates and normalizes node execution outputs into a clean final response.

        Args:
            raw_response: Raw response string from node.
            route: Executed route ('RAG' or 'MCP').
            citations: Document citations if from RAG.
            tool_calls: Tool execution details if from MCP.
            error: Exception error string if failure occurred.
            start_time: Start timestamp for duration calculation.

        Returns:
            Dictionary containing 'formatted_response', 'duration', and 'metadata'.
        """
        end_time = time.time()
        duration = round(end_time - start_time, 3) if start_time else 0.0
        logger.info(f"SupervisorAgent formatting final response for route '{route}' (duration={duration}s)...")

        if error:
            formatted_text = f"⚠️ System Exception during execution:\n{error}\n\nPlease verify your setup and try again."
            return {
                "formatted_response": formatted_text,
                "duration": duration,
                "status": "error",
            }

        text = raw_response or "No output generated by subsystem."

        # Format RAG response with citations if available
        if route == "RAG" and citations:
            citation_lines = []
            for idx, cite in enumerate(citations, 1):
                source = cite.get("source", "Unknown Document")
                page = cite.get("page", 1)
                citation_lines.append(f"  [{idx}] 📄 {source} (Page {page})")
            
            if citation_lines and "Sources & Citations" not in text:
                text += "\n\n📌 **Sources & Citations**:\n" + "\n".join(citation_lines)

        # Format MCP response with tool execution notes if available
        elif route == "MCP" and tool_calls:
            tool_names = [tc.get("name") for tc in tool_calls if tc.get("name")]
            if tool_names:
                text += f"\n\n🛠️ *Executed via MCP Tool*: `{', '.join(tool_names)}`"

        return {
            "formatted_response": text,
            "duration": duration,
            "status": "success",
        }
